export function listFailures(topologyId: string): FailureScenario[] {
  return ALL_FAILURES.filter((s) => s.topologies.includes(topologyId))
}

export function getFailure(id: string): FailureScenario | undefined {
  return ALL_FAILURES.find((s) => s.id === id)
}

/** Resolve SimState.failures into the down devices / links / interfaces
 *  the engine must honour, merged with any explicitly set down lists. */
export function resolveDown(state: SimState): {
  downDevices: Set<string>
  downInterfaces: Set<string>
  downLinks: Set<string>
} {
  const downDevices = new Set(state.downDevices)
  const downLinks = new Set(state.downLinks)
  const downInterfaces = new Set(state.downInterfaces)
  for (const fid of state.failures ?? []) {
    const sc = getFailure(fid)
    if (!sc) continue
    for (const d of sc.downDevices ?? []) downDevices.add(d)
    for (const l of sc.downLinks ?? []) downLinks.add(l)
    for (const i of sc.downInterfaces ?? []) downInterfaces.add(i)
  }
  return { downDevices, downInterfaces, downLinks }
}
