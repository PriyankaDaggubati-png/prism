function vrrpRouter(id: string, host: string, x: number, master: boolean): Device {
  const pri = master ? 120 : 100
  const self = master ? '.1' : '.2'
  const sub = (vlan: number, net: string) =>
    iface(id, `GigabitEthernet0/0.${vlan}`, {
      description: `dot1Q ${vlan}, VRRP ${vlan} VIP ${net}.254 priority ${pri} preempt`,
      ip: `${net}${self}`,
      mask: '255.255.255.0',
      mode: 'trunk',
      vlan,
    })
  return {
    config: `interface GigabitEthernet0/0\n no ip address\ninterface GigabitEthernet0/0.10\n encapsulation dot1Q 10\n ip address 192.168.10.${master ? 1 : 2} 255.255.255.0\n vrrp 10 ip 192.168.10.254\n vrrp 10 priority ${pri}\n vrrp 10 preempt\ninterface GigabitEthernet0/0.20\n encapsulation dot1Q 20\n ip address 192.168.20.${master ? 1 : 2} 255.255.255.0\n vrrp 20 ip 192.168.20.254\n vrrp 20 priority ${pri}\n vrrp 20 preempt\ninterface GigabitEthernet0/0.30\n encapsulation dot1Q 30\n ip address 192.168.30.${master ? 1 : 2} 255.255.255.0\n vrrp 30 ip 192.168.30.254\n vrrp 30 priority ${pri}\n vrrp 30 preempt`,
    cpuPct: master ? 14 : 9,
    hostname: host,
    id,
    interfaces: [
      iface(id, 'GigabitEthernet0/0', { description: 'Trunk to SW1, no IP address', mode: 'trunk' }),
      sub(10, '192.168.10'), sub(20, '192.168.20'), sub(30, '192.168.30'),
    ],
    kind: 'router',
    memPct: 27,
    model: 'Cisco 4300 series (lab, GNS3)',
    notes: master ? 'VRRP master, priority 120, preempt, for groups 10, 20 and 30.' : 'VRRP backup, priority 100, preempt, for groups 10, 20 and 30.',
    position: [x, 3, 0],
    role: master ? 'VRRP master (ROAS)' : 'VRRP backup (ROAS)',
    routes: [
      route('192.168.10.0', '255.255.255.0', 'connected', 'GigabitEthernet0/0.10', 'connected', 0),
      route('192.168.20.0', '255.255.255.0', 'connected', 'GigabitEthernet0/0.20', 'connected', 0),
      route('192.168.30.0', '255.255.255.0', 'connected', 'GigabitEthernet0/0.30', 'connected', 0),
    ],
    vrrpGroups: [10, 20, 30].map((g) => ({
      id: g,
      interface: `GigabitEthernet0/0.${g}`,
      priority: pri,
      state: master ? 'Master' : 'Backup',
      virtualIp: `192.168.${g}.254`,
    })),
  }
}

